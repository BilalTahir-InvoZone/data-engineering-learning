def save_to_csv(df):
    """
    Save the processed DataFrame as a CSV file.
    """

    print("=" * 70)
    print("LOAD - SAVE PROCESSED DATASET AS CSV")
    print("=" * 70)

    # Create the output directory if it doesn't exist.
    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    # Define the output CSV file.
    output_file = OUTPUT_DIR / "processed_dataset.csv"

    # Save the DataFrame.
    #
    # index=False is important.
    #
    # Without it, Pandas would add its DataFrame index
    # as an extra column in the CSV.
    df.to_csv(
        output_file,
        index=False
    )

    print(
        f"CSV file saved successfully:"
    )

    print(
        output_file
    )

    print(
        f"Rows saved    : {len(df):,}"
    )

    print(
        f"Columns saved : {len(df.columns):,}"
    )

    print()

    return output_file


