def validate_records(df):
    """
    Validate records using business rules.

    This step does NOT simply check data types.
    It checks whether the data makes business sense.

    Examples:

        number_of_employees >= 0
        quantity > 0
        unit_price >= 0
        amount >= 0
        order_amount >= 0
        discount between 0 and 100
    """

    print("=" * 70)
    print("TRANSFORM - VALIDATE INVALID RECORDS")
    print("=" * 70)

    # --------------------------------------------------------
    # Create a mask containing invalid records.
    #
    # A mask is simply True / False for every row.
    # --------------------------------------------------------

    invalid_mask = pd.Series(
        False,
        index=df.index
    )

    # --------------------------------------------------------
    # Rule 1:
    # Number of employees cannot be negative.
    # --------------------------------------------------------

    if "number_of_employees" in df.columns:

        invalid_employee_count = (
            df["number_of_employees"] < 0
        )

        print(
            "Invalid employee counts:",
            invalid_employee_count.sum()
        )

        invalid_mask = (
            invalid_mask |
            invalid_employee_count
        )

    # --------------------------------------------------------
    # Rule 2:
    # Quantity should be greater than zero.
    # --------------------------------------------------------

    if "quantity" in df.columns:

        invalid_quantity = (
            df["quantity"] <= 0
        )

        print(
            "Invalid quantities:",
            invalid_quantity.sum()
        )

        invalid_mask = (
            invalid_mask |
            invalid_quantity
        )

    # --------------------------------------------------------
    # Rule 3:
    # Unit price cannot be negative.
    # --------------------------------------------------------

    if "unit_price" in df.columns:

        invalid_unit_price = (
            df["unit_price"] < 0
        )

        print(
            "Invalid unit prices:",
            invalid_unit_price.sum()
        )

        invalid_mask = (
            invalid_mask |
            invalid_unit_price
        )

    # --------------------------------------------------------
    # Rule 4:
    # Amount cannot be negative.
    # --------------------------------------------------------

    if "amount" in df.columns:

        invalid_amount = (
            df["amount"] < 0
        )

        print(
            "Invalid amounts:",
            invalid_amount.sum()
        )

        invalid_mask = (
            invalid_mask |
            invalid_amount
        )

    # --------------------------------------------------------
    # Rule 5:
    # Order amount cannot be negative.
    #
    # Remember that order_amount was intentionally allowed
    # to remain NULL earlier.
    #
    # Therefore we only consider NEGATIVE values invalid.
    # --------------------------------------------------------

    if "order_amount" in df.columns:

        invalid_order_amount = (
            df["order_amount"] < 0
        )

        print(
            "Invalid order amounts:",
            invalid_order_amount.sum()
        )

        invalid_mask = (
            invalid_mask |
            invalid_order_amount
        )

    # --------------------------------------------------------
    # Rule 6:
    # Discount must be between 0 and 100.
    #
    # Example:
    #
    # 10  -> valid
    # 50  -> valid
    # 100 -> valid
    # -5  -> invalid
    # 150 -> invalid
    # --------------------------------------------------------

    if "discount" in df.columns:

        invalid_discount = (
            (df["discount"] < 0) |
            (df["discount"] > 100)
        )

        print(
            "Invalid discounts:",
            invalid_discount.sum()
        )

        invalid_mask = (
            invalid_mask |
            invalid_discount
        )

    # --------------------------------------------------------
    # Count all invalid records.
    # --------------------------------------------------------

    invalid_records = df[
        invalid_mask
    ].copy()

    print()
    print(
        "Total invalid records:",
        len(invalid_records)
    )

    # --------------------------------------------------------
    # Display invalid records.
    #
    # We only display a few important columns instead of all
    # 127 columns.
    # --------------------------------------------------------

    if len(invalid_records) > 0:

        print()
        print("Sample invalid records:")

        columns_to_display = [
            "company_id",
            "number_of_employees",
            "quantity",
            "amount",
            "unit_price",
            "order_amount",
            "discount"
        ]

        existing_columns = [
            column
            for column in columns_to_display
            if column in invalid_records.columns
        ]

        print(
            invalid_records[
                existing_columns
            ].head(10)
        )

    else:

        print(
            "No invalid records found."
        )

    print()

    # --------------------------------------------------------
    # IMPORTANT:
    #
    # We are NOT deleting invalid records yet.
    #
    # In a real ETL pipeline we might:
    #
    # 1. Fix the value
    # 2. Reject the record
    # 3. Send it to a quarantine table
    # 4. Send it to a data-quality/error file
    #
    # For this learning project, we'll return the dataframe
    # unchanged and handle the invalid records explicitly.
    # --------------------------------------------------------

    return df, invalid_records

