def handle_missing_values(df):
    """
    Handle missing/null values according to column-specific
    business rules.

    Important:
    We don't treat every missing value in the same way.

    Rules for this exercise:

        company_name -> "Unknown"
        city         -> "Unknown"
        email        -> "Unknown"

        discount     -> 0

    order_amount is intentionally left unchanged because
    a missing order amount does NOT necessarily mean zero.
    """

    print("=" * 70)
    print("TRANSFORM - HANDLE MISSING VALUES")
    print("=" * 70)

    # --------------------------------------------------------
    # Count missing values BEFORE cleaning.
    # --------------------------------------------------------

    missing_before = (
        df.isnull()
        .sum()
        .sum()
    )

    print(
        f"Total missing values before cleaning: "
        f"{missing_before:,}"
    )

    print()


    # --------------------------------------------------------
    # 1. Handle company_name
    #
    # If company_name is missing, use "Unknown".
    # --------------------------------------------------------

    if "company_name" in df.columns:

        df["company_name"] = (
            df["company_name"]
            .fillna("Unknown")
        )


    # --------------------------------------------------------
    # 2. Handle city
    #
    # If city is missing, use "Unknown".
    # --------------------------------------------------------

    if "city" in df.columns:

        df["city"] = (
            df["city"]
            .fillna("Unknown")
        )


    # --------------------------------------------------------
    # 3. Handle email
    #
    # If email is missing, use "Unknown".
    # --------------------------------------------------------

    if "email" in df.columns:

        df["email"] = (
            df["email"]
            .fillna("Unknown")
        )


    # --------------------------------------------------------
    # 4. Handle discount
    #
    # For this dataset, a missing discount means:
    #
    # "There is no discount."
    #
    # Therefore NULL becomes 0.
    # --------------------------------------------------------

    if "discount" in df.columns:

        df["discount"] = (
            df["discount"]
            .fillna(0)
        )


    # --------------------------------------------------------
    # 5. order_amount
    #
    # We intentionally DO NOT replace missing values here.
    #
    # Why?
    #
    # NULL order_amount could mean:
    #
    # - source data was incomplete
    # - order amount was not calculated
    # - data ingestion failed
    #
    # Replacing it with 0 would create fake business data.
    # --------------------------------------------------------

    print(
        "order_amount missing values were intentionally "
        "left unchanged."
    )

    print()


    # --------------------------------------------------------
    # Count missing values AFTER cleaning.
    # --------------------------------------------------------

    missing_after = (
        df.isnull()
        .sum()
        .sum()
    )

    print(
        f"Total missing values after cleaning: "
        f"{missing_after:,}"
    )

    print()


    # --------------------------------------------------------
    # Show remaining columns containing NULL values.
    # --------------------------------------------------------

    remaining_missing = (
        df.isnull()
        .sum()
    )

    remaining_missing = (
        remaining_missing[
            remaining_missing > 0
        ]
        .sort_values(
            ascending=False
        )
    )


    if len(remaining_missing) > 0:

        print(
            "Remaining missing values:"
        )

        print(
            remaining_missing
        )

    else:

        print(
            "No missing values remain."
        )

    print()


    return df

