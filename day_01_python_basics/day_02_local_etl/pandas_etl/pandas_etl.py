def standardize_column_names(df):
    """
    Standardize DataFrame column names.

    Rules:

    1. Convert names to lowercase.
    2. Remove leading/trailing spaces.
    3. Replace spaces with underscores.
    4. Replace hyphens with underscores.
    5. Remove special characters.
    6. Make sure multiple underscores are collapsed.

    Example:

        "Company Name" -> "company_name"
        "Order Amount" -> "order_amount"
        "Customer-ID"  -> "customer_id"
    """

    print("=" * 70)
    print("TRANSFORM - STANDARDIZE COLUMN NAMES")
    print("=" * 70)

    print(
        f"Columns before standardization: "
        f"{len(df.columns)}"
    )

    print()

    # --------------------------------------------------------
    # Standardize every column name.
    # --------------------------------------------------------

    df.columns = (
        df.columns

        # Convert to string.
        .astype(str)

        # Remove spaces from beginning/end.
        .str.strip()

        # Convert to lowercase.
        .str.lower()

        # Replace spaces with underscores.
        .str.replace(
            " ",
            "_",
            regex=False
        )

        # Replace hyphens with underscores.
        .str.replace(
            "-",
            "_",
            regex=False
        )

        # Remove characters other than:
        # a-z, 0-9 and underscore.
        .str.replace(
            r"[^a-z0-9_]",
            "",
            regex=True
        )

        # Replace multiple underscores with one.
        .str.replace(
            r"_+",
            "_",
            regex=True
        )

        # Remove leading/trailing underscores.
        .str.strip("_")
    )

    print(
        "Column names standardized successfully."
    )

    print()

    # --------------------------------------------------------
    # Display the first 30 column names after cleaning.
    # --------------------------------------------------------

    print("First 30 standardized columns:")

    for number, column in enumerate(
        df.columns[:30],
        start=1
    ):

        print(
            f"{number:3}. {column}"
        )

    print()

    print(
        f"Columns after standardization: "
        f"{len(df.columns)}"
    )

    print()

    return df

