def convert_data_types(df):
    """
    Convert important columns to their correct data types.

    Integer columns:
        company_id
        number_of_employees
        contact_id
        deal_id
        quantity

    Numeric columns:
        amount
        unit_price
        order_amount
        discount

    Boolean columns:
        is_active

    Date columns:
        close_date
        order_date
        created_date
        updated_date
    """

    print("=" * 70)
    print("TRANSFORM - CONVERT DATA TYPES")
    print("=" * 70)


    # ========================================================
    # INTEGER COLUMNS
    # ========================================================

    integer_columns = [
        "company_id",
        "number_of_employees",
        "contact_id",
        "deal_id",
        "quantity"
    ]


    for column in integer_columns:

        if column in df.columns:

            # ------------------------------------------------
            # Use pandas nullable integer type.
            #
            # "Int64" is different from normal "int64".
            #
            # Pandas "Int64" can represent:
            #
            #     10
            #     20
            #     <NA>
            #
            # This is useful when a column contains missing
            # values.
            # ------------------------------------------------

            df[column] = pd.to_numeric(
                df[column],
                errors="coerce"
            ).astype("Int64")


    # ========================================================
    # FLOAT / NUMERIC COLUMNS
    # ========================================================

    numeric_columns = [
        "amount",
        "unit_price",
        "order_amount",
        "discount"
    ]


    for column in numeric_columns:

        if column in df.columns:

            # ------------------------------------------------
            # Convert values to numeric.
            #
            # errors="coerce" means:
            #
            # If Pandas finds something that isn't a valid
            # number, it converts it to NaN instead of
            # crashing the entire pipeline.
            # ------------------------------------------------

            df[column] = pd.to_numeric(
                df[column],
                errors="coerce"
            )


    # ========================================================
    # BOOLEAN COLUMNS
    # ========================================================

    if "is_active" in df.columns:

        # Convert to Pandas nullable Boolean type.
        df["is_active"] = (
            df["is_active"]
            .astype("boolean")
        )


    # ========================================================
    # DATE COLUMNS
    # ========================================================

    date_columns = [
        "close_date",
        "order_date",
        "created_date",
        "updated_date"
    ]


    for column in date_columns:

        if column in df.columns:

            # ------------------------------------------------
            # Convert string/date values to Pandas datetime.
            #
            # Invalid dates become NaT.
            #
            # NaT means:
            #
            # "Not a Time"
            # ------------------------------------------------

            df[column] = pd.to_datetime(
                df[column],
                errors="coerce"
            )


    # ========================================================
    # DISPLAY RESULTING DATA TYPES
    # ========================================================

    print("Data types after conversion:")

    columns_to_display = [
        "company_id",
        "number_of_employees",
        "contact_id",
        "deal_id",
        "quantity",
        "amount",
        "unit_price",
        "order_amount",
        "discount",
        "is_active",
        "close_date",
        "order_date",
        "created_date",
        "updated_date"
    ]


    existing_columns = [
        column
        for column in columns_to_display
        if column in df.columns
    ]


    print(
        df[
            existing_columns
        ].dtypes
    )

    print()


    return df

