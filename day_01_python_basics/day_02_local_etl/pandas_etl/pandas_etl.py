def remove_duplicates(df):
    """
    Remove completely duplicate rows.

    A duplicate means that all column values in one row
    are exactly the same as another row.

    Example:

        company_id | city     | amount
        -----------|----------|--------
        13         | Lahore   | 5000
        17         | Karachi  | 7000
        13         | Lahore   | 5000   <-- duplicate

    After drop_duplicates(), only one copy remains.
    """

    print("=" * 70)
    print("TRANSFORM - REMOVE DUPLICATES")
    print("=" * 70)

    # --------------------------------------------------------
    # Count duplicates BEFORE removing them.
    # --------------------------------------------------------

    duplicate_count = (
        df.duplicated()
        .sum()
    )

    print(
        f"Duplicate rows found: "
        f"{duplicate_count:,}"
    )


    # --------------------------------------------------------
    # Remove duplicate rows.
    #
    # We use inplace=False implicitly, meaning Pandas
    # returns a new DataFrame.
    # --------------------------------------------------------

    df_cleaned = (
        df.drop_duplicates()
    )


    # --------------------------------------------------------
    # Calculate how many rows were removed.
    # --------------------------------------------------------

    rows_removed = (
        len(df)
        - len(df_cleaned)
    )


    print(
        f"Rows removed: "
        f"{rows_removed:,}"
    )


    print(
        f"Rows before: "
        f"{len(df):,}"
    )


    print(
        f"Rows after: "
        f"{len(df_cleaned):,}"
    )


    print()


    return df_cleaned

